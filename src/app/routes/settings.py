# database facts
# ---------------------------------------------------------------------------
def _count(sql: str) -> int | None:
    try:
        row = db.fetch_one(sql)
    except sqlite3.Error:  # pragma: no cover
        return None
    return int(row[0]) if row else 0


def database_facts() -> dict:
    path = Path(db.current_database_path())
    conn = db.get_db()
    try:
        journal = str(conn.execute("PRAGMA journal_mode").fetchone()[0])
        page_size = int(conn.execute("PRAGMA page_size").fetchone()[0])
        page_count = int(conn.execute("PRAGMA page_count").fetchone()[0])
        foreign_keys = bool(conn.execute("PRAGMA foreign_keys").fetchone()[0])
    except sqlite3.Error as exc:  # pragma: no cover
        log.warning("could not read pragmas: %r", exc)
        journal, page_size, page_count, foreign_keys = "?", 0, 0, False

    try:
        on_disk = path.stat().st_size
    except OSError:  # pragma: no cover - :memory: or a fresh file
        on_disk = page_size * page_count

    return {
        "app": current_app.config["APP_NAME"],
        "version": current_app.config["VERSION"],
        "port": current_app.config["PORT"],
        "path": str(path),
        "size_mb": round(on_disk / 1_048_576, 1),
        "journal_mode": journal,
        "foreign_keys": foreign_keys,
        "migrations": db.applied_migrations(conn),
        "counts": {
            "pages": _count("SELECT COUNT(*) FROM pages"),
            "ads": _count("SELECT COUNT(*) FROM ads"),
            "ads_active": _count("SELECT COUNT(*) FROM ads WHERE status='active'"),
            "ad_versions": _count("SELECT COUNT(*) FROM ad_versions"),
            "products": _count("SELECT COUNT(*) FROM products"),
            "groups": _count("SELECT COUNT(*) FROM \"groups\""),
            "transcripts": _count("SELECT COUNT(*) FROM transcripts"),
            "jobs": _count("SELECT COUNT(*) FROM jobs"),
            "test_queue": _count(
                "SELECT COUNT(*) FROM test_queue_items WHERE deleted_at IS NULL"
            ),
            "shortlisted": _count("SELECT COUNT(*) FROM winner_shortlist"),
        },
    }


def _worker_token() -> str:
    """The extension's token. Delegated to the P0 service so there is exactly
    one generator; if that module is unavailable the card degrades to a notice
    rather than inventing a second token scheme."""
    try:
        from .. import job_service
    except ImportError:  # pragma: no cover
        return ""
    try:
        return str(job_service.worker_token())
    except Exception as exc:  # pragma: no cover - never leak the value
        log.warning("worker token unavailable: %s", type(exc).__name__)
        return ""


