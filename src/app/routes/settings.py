log = logging.getLogger("adspy2.settings")

bp = Blueprint("settings", __name__)

SECTIONS: tuple[tuple[str, str, str], ...] = (
    ("appearance", "Appearance", "sun"),
    ("worker", "Worker access", "queue"),
    ("keys", "API keys", "settings"),
    ("blocked", "Blocked pages", "pages"),
    ("backups", "Backups", "report"),
    ("database", "Database", "info"),
    ("dataset", "Data version", "info"),
)
SECTION_KEYS = tuple(key for key, _, _ in SECTIONS)

# key in `settings`, label, where the provider docs call it, env fallback
API_KEYS: tuple[tuple[str, str, str], ...] = (
    ("groq_api_key", "Groq", "GROQ_API_KEY"),
    ("sarvam_api_key", "Sarvam", "SARVAM_API_KEY"),
    # Legacy: v2's transcription never calls Gemini (app/transcription.py runs
    # a "gemini" choice as Groq whisper-large-v3 — the live A/B found turbo /
    # Gemini garbled Hindi). The row stays so an old stored key can be cleared.
    ("gemini_api_key", "Gemini (legacy, not used)", "GEMINI_API_KEY"),
)

# What the "Default provider" select offers. Gemini is deliberately absent:
# a stored "gemini" value is honoured as Groq with a note in the product panel.
PROVIDERS: tuple[tuple[str, str], ...] = (
    ("groq", "Groq (whisper-large-v3)"), ("sarvam", "Sarvam (Indic)"),
)

BLOCKED_PAGE_SIZE = 25


@bp.record_once
def _ensure_session_key(state) -> None:
    app = state.app
    if not app.config.get("SECRET_KEY"):
        app.config["SECRET_KEY"] = (
            os.environ.get("ADSPY2_SECRET_KEY") or py_secrets.token_hex(32)
        )


# ---------------------------------------------------------------------------
# settings table helpers
# ---------------------------------------------------------------------------
def _get(key: str, default: str = "") -> str:
    row = db.fetch_one("SELECT value FROM settings WHERE key = ?", (key,))
    return default if row is None else str(row["value"])


def _updated_at(key: str) -> str:
    row = db.fetch_one("SELECT updated_at FROM settings WHERE key = ?", (key,))
    return "" if row is None else str(row["updated_at"])


def _set(key: str, value: str) -> None:
    with db.transaction():
        db.execute(
            """
            INSERT INTO settings(key, value, updated_at) VALUES(?,?,?)
            ON CONFLICT(key) DO UPDATE SET value = excluded.value,
                                           updated_at = excluded.updated_at
            """,
            (key, str(value), utc_now()),
        )


def mask(value: str) -> str:
    """A secret, shown the only way a secret should be: enough to recognise it,
    not enough to use it. Never returns more than the last four characters."""
    text = str(value or "").strip()
    if not text:
        return ""
    if len(text) <= 8:
        return "•" * 8
    return "•" * 8 + text[-4:]


def api_key_rows() -> list[dict]:
    rows = []
    for key, label, env_name in API_KEYS:
        stored = _get(key)
        from_env = os.environ.get(env_name, "").strip()
        rows.append(
            {
                "key": key,
                "label": label,
                "env_name": env_name,
                "configured": bool(stored),
                "masked": mask(stored),
                "updated_at": _updated_at(key) if stored else "",
                "env_fallback": bool(from_env) and not stored,
            }
        )
    return rows


# ---------------------------------------------------------------------------
# blocked + hidden pages
# ---------------------------------------------------------------------------
def blocked_pages(search: str = "", page: int = 1) -> dict:
    where, params = "", []
    if search.strip():
        where = (
            " WHERE b.page_name_snapshot LIKE ? COLLATE NOCASE"
            " OR b.platform_page_id LIKE ?"
            " OR b.reason LIKE ? COLLATE NOCASE"
        )
        needle = f"%{search.strip()}%"
        params = [needle, needle, needle]

    total_row = db.fetch_one(
        f"SELECT COUNT(*) AS n FROM blocked_pages b{where}", params
    )
    total = int(total_row["n"]) if total_row else 0
    pages = max(1, -(-total // BLOCKED_PAGE_SIZE))
    page = max(1, min(int(page), pages))
    rows = [
        dict(row)
        for row in db.fetch_all(
            f"""
            SELECT b.*, p.name AS live_name
              FROM blocked_pages b
              LEFT JOIN pages p ON p.id = b.page_id
              {where}
             ORDER BY b.created_at DESC, b.id DESC
             LIMIT ? OFFSET ?
            """,
            [*params, BLOCKED_PAGE_SIZE, (page - 1) * BLOCKED_PAGE_SIZE],
        )
    ]
    return {"rows": rows, "total": total, "page": page, "pages": pages,
            "start": 0 if not total else (page - 1) * BLOCKED_PAGE_SIZE + 1,
            "end": min(page * BLOCKED_PAGE_SIZE, total)}


def hidden_pages() -> list[dict]:
    return [
        dict(row)
        for row in db.fetch_all(
            """
            SELECT id, name, platform_page_id, active_ads, updated_at
              FROM pages WHERE is_hidden = 1
             ORDER BY name COLLATE NOCASE
             LIMIT 200
            """
        )
    ]


# ---------------------------------------------------------------------------
# backups
# ---------------------------------------------------------------------------
def backup_dir() -> Path:
    return Path(db.current_database_path()).parent / "backups"


def _sync_backups_from_disk() -> None:
    """Files first, table second. A snapshot someone made with `cp` is still a
    backup; the table exists so the card can list them, not to own them."""
    folder = backup_dir()
    if not folder.is_dir():
        return
    now = utc_now()
    try:
        found = sorted(folder.glob("*.sqlite3"))
    except OSError:  # pragma: no cover - unreadable directory
        return
    with db.transaction():
        for path in found:
            try:
                size = path.stat().st_size
            except OSError:  # pragma: no cover
                continue
            db.execute(
                """
                INSERT INTO backups(filename, size_bytes, reason, created_at)
                VALUES(?,?,'manual',?)
                ON CONFLICT(filename) DO UPDATE SET size_bytes = excluded.size_bytes
                """,
                (path.name, size, now),
            )
        # A row whose file was deleted underneath us is noise, not history.
        names = {path.name for path in found}
        for row in db.fetch_all("SELECT id, filename FROM backups"):
            if str(row["filename"]) not in names:
                db.execute("DELETE FROM backups WHERE id = ?", (int(row["id"]),))


def backup_rows() -> list[dict]:
    _sync_backups_from_disk()
    rows = [dict(row) for row in db.fetch_all(
        "SELECT * FROM backups ORDER BY created_at DESC, id DESC LIMIT 50"
    )]
    for row in rows:
        row["size_mb"] = round(int(row["size_bytes"] or 0) / 1_048_576, 1)
    return rows


