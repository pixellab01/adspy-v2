"""Settings — everything v1's Settings screen did, minus the half that needed
accounts.

v1's /settings (services/settings_api.py) is three cards: "My account",
"Login accounts" (add a user, set Normal/Admin) and "Blocked pages". Decision
#4 deletes the first two outright — v2 has no login, no users and no roles, so
there is nothing to manage and no role to assign. Blocked pages survives
column for column: Page, Page ID, Reason, Blocked, and the Unblock button.

The rest of this screen is the settings v1 kept scattered somewhere else and
the owner still needs:

  Appearance      the black / light theme switch (v1 put it in the topbar only)
  Worker access   the shared token the Chrome extension authenticates with,
                  generated by app/job_service.py::worker_token
  API keys        the transcription providers v1 read out of
                  services/transcribe_providers.py — Gemini, Groq, Sarvam
  Blocked pages   v1's card, plus the hidden pages the Page Analyzer hides
  Backups         v1 had six .sqlite3 snapshots in a folder and nothing that
                  knew about them; 002 added the table, this makes them
  Database        the facts /health returns, on a screen instead of in JSON
  Data version    OLD DATA / NEW DATA — which file is live, both files' row
                  counts, the switch, and the one-time "create" (app/dataset.py)

SECRETS DISCIPLINE. The three provider keys and the worker token are the only
secrets this app holds. They are never rendered in full (the worker token is
behind a collapsed disclosure because its whole purpose is to be copied into
the extension), never written to a log line, and never echoed back in a flash
message or an error — if you add a code path here that touches ``value``, it
must not end up in ``log.*`` or in ``flash()``.
"""

from __future__ import annotations

