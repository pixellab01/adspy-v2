@bp.get("/settings")
def settings_page():
    section = str(request.args.get("section") or "appearance").lower()
    if section not in SECTION_KEYS:
        section = "appearance"

    context = {
        "active_nav": "settings",
        "sections": SECTIONS,
        "section": section,
        "rail": [(key, label, url_for("settings.settings_page", section=key), icon)
                 for key, label, icon in SECTIONS],
    }
    if section == "worker":
        token = _worker_token()
        context.update(token=token, token_masked=mask(token),
                       token_updated=_updated_at("worker_token"),
                       queue_paused=_get("queue_paused") == "1")
    elif section == "keys":
        context.update(api_keys=api_key_rows(),
                       providers=PROVIDERS,
                       provider=_get("transcription_provider", "groq"))
    elif section == "blocked":
        context.update(
            blocked=blocked_pages(request.args.get("q", ""),
                                  int(request.args.get("page", 1) or 1)),
            hidden=hidden_pages(),
            q=request.args.get("q", ""),
        )
    elif section == "backups":
        context.update(backups=backup_rows(), backup_dir=str(backup_dir()))
    elif section == "database":
        context.update(facts=database_facts())
    elif section == "dataset":
        context.update(
            datasets=[dataset.facts(name) for name in ("old", "new")],
            carry_over_keys=dataset.CARRY_OVER_KEYS,
        )
    return render_template("settings.html", **context)


