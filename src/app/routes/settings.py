@bp.post("/settings/worker-token/rotate")
def rotate_worker_token():
    """A new token. The extension stops working until you paste the new one in,
    which is the point: this is how you lock out a browser profile you no
    longer control."""
    _set("worker_token", py_secrets.token_urlsafe(32))
    log.info("worker token rotated")          # the event, never the value
    flash("Worker token rotated. Paste the new token into the extension.",
          "warning")
    return redirect(url_for("settings.settings_page", section="worker"))


@bp.post("/settings/api-keys")
def save_api_keys():
    """Blank means "leave it alone", so a form round-trip never wipes a key you
    could not see. The values never reach a log line or a flash message."""
    changed = []
    for key, label, _env in API_KEYS:
        value = str(request.form.get(key) or "").strip()
        if value:
            _set(key, value)
            changed.append(label)
    provider = str(request.form.get("transcription_provider") or "").strip().lower()
    if provider in {name for name, _ in PROVIDERS}:
        _set("transcription_provider", provider)

    if changed:
        log.info("api keys updated: %s", ", ".join(changed))
        flash(f"Saved {', '.join(changed)} key.", "success")
    else:
        flash("Default provider saved. Blank fields left the stored keys alone.",
              "success")
    return redirect(url_for("settings.settings_page", section="keys"))


@bp.post("/settings/api-keys/clear")
def clear_api_key():
    key = str(request.form.get("key") or "")
    labels = {name: label for name, label, _ in API_KEYS}
    if key not in labels:
        flash("Unknown API key.", "error")
        return redirect(url_for("settings.settings_page", section="keys"))
    with db.transaction():
        db.execute("DELETE FROM settings WHERE key = ?", (key,))
    log.info("api key cleared: %s", labels[key])
    flash(f"{labels[key]} key removed.", "success")
    return redirect(url_for("settings.settings_page", section="keys"))


@bp.post("/settings/blocked/<int:blocked_id>/unblock")
def unblock_page(blocked_id: int):
    row = db.fetch_one(
        "SELECT page_name_snapshot, page_id FROM blocked_pages WHERE id = ?",
        (blocked_id,),
    )
    if row is None:
        flash("That page is not blocked.", "error")
        return redirect(url_for("settings.settings_page", section="blocked"))
    with db.transaction():
        db.execute("DELETE FROM blocked_pages WHERE id = ?", (blocked_id,))
        if row["page_id"] is not None:
            db.execute(
                "UPDATE pages SET is_hidden = 0, updated_at = ? WHERE id = ?",
                (utc_now(), int(row["page_id"])),
            )
    flash(f"{row['page_name_snapshot'] or 'Page'} unblocked. Nothing was deleted.",
          "success")
    return redirect(request.form.get("next")
                    or url_for("settings.settings_page", section="blocked"))


@bp.post("/settings/pages/<int:page_id>/unhide")
def unhide_page(page_id: int):
    row = db.fetch_one("SELECT name FROM pages WHERE id = ?", (page_id,))
    if row is None:
        flash("No such page.", "error")
        return redirect(url_for("settings.settings_page", section="blocked"))
    with db.transaction():
        db.execute(
            "UPDATE pages SET is_hidden = 0, updated_at = ? WHERE id = ?",
            (utc_now(), page_id),
        )
    flash(f"{row['name']} is visible again.", "success")
    return redirect(request.form.get("next")
                    or url_for("settings.settings_page", section="blocked"))


@bp.post("/settings/backups/create")
def create_backup():
    """``VACUUM INTO`` — the only correct way to copy a live WAL database.
    Never a file copy: the -wal file holds committed pages the .sqlite3 file
    does not, so `cp` gives you a snapshot that is quietly missing writes."""
    folder = backup_dir()
    try:
        folder.mkdir(parents=True, exist_ok=True)
    except OSError as exc:
        flash(f"Could not create {folder}: {exc}", "error")
        return redirect(url_for("settings.settings_page", section="backups"))

    stamp = utc_now().replace(":", "").replace("-", "").replace("T", "-")[:15]
    # Both datasets back up into the same folder, so the name says which one
    # this snapshot is of — an OLD and a NEW snapshot must never look alike.
    prefix = f"{dataset.active()}-adspy2"
    target = folder / f"{prefix}-{stamp}.sqlite3"
    if target.exists():
        target = folder / f"{prefix}-{stamp}-{py_secrets.token_hex(2)}.sqlite3"

    try:
        # VACUUM cannot run inside a transaction; db.connect() uses
        # isolation_level=None, so this statement stands alone.
        db.get_db().execute("VACUUM INTO ?", (str(target),))
    except sqlite3.Error as exc:
        log.warning("backup failed: %r", exc)
        flash(f"Backup failed: {exc}", "error")
        return redirect(url_for("settings.settings_page", section="backups"))

    size = target.stat().st_size if target.exists() else 0
    with db.transaction():
        db.execute(
            """
            INSERT INTO backups(filename, size_bytes, reason, created_at)
            VALUES(?,?,'manual',?)
            ON CONFLICT(filename) DO UPDATE SET size_bytes = excluded.size_bytes
            """,
            (target.name, size, utc_now()),
        )
    flash(f"Backup written: {target.name} ({round(size / 1_048_576, 1)} MB).",
          "success")
    return redirect(url_for("settings.settings_page", section="backups"))


@bp.post("/settings/backups/<int:backup_id>/delete")
def delete_backup(backup_id: int):
    row = db.fetch_one("SELECT filename FROM backups WHERE id = ?", (backup_id,))
    if row is None:
        flash("No such backup.", "error")
        return redirect(url_for("settings.settings_page", section="backups"))
    target = backup_dir() / str(row["filename"])
    try:
        if target.is_file():
            target.unlink()
    except OSError as exc:
        flash(f"Could not delete {target.name}: {exc}", "error")
        return redirect(url_for("settings.settings_page", section="backups"))
    with db.transaction():
        db.execute("DELETE FROM backups WHERE id = ?", (backup_id,))
    flash(f"Deleted {row['filename']}.", "success")
    return redirect(url_for("settings.settings_page", section="backups"))


